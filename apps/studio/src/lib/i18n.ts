export const useLanguage = create<{
  language: 'id' | 'en';
  setLanguage: (language: 'id' | 'en') => void;
}>((set) => ({
  language: localStorage.getItem('uc-language') === 'en' ? 'en' : 'id',
  setLanguage: (language) => {
    localStorage.setItem('uc-language', language);
    document.documentElement.lang = language;
    set({ language });
  },
}));

export function useText() {
  return useLanguage((state) => state.language) === 'en' ? en : id;
}
